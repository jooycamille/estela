import { copyFileSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";
import sharp from "sharp";
import { COLORS, markSvgInner } from "./mark.mjs";

// Regenerates every logo file in public/brand from mark.mjs (icon) and the Nunito typeface (wordmark).
// Run: npm run brand. Then copy public/brand/heyjoy-mark.svg to public/favicon.svg if the icon changed.

const out = process.argv[2] ?? "public/brand";
mkdirSync(out, { recursive: true });
const font = (w) => {
  const b = readFileSync(`node_modules/@fontsource/nunito/files/nunito-latin-${w}-normal.woff`);
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};
const black = font(900), bold = font(800);

/** Text as outlined path data (so the logo never depends on installed fonts). */
function text(f, str, x, baseline, size) {
  const p = f.getPath(str, x, baseline, size);
  const bb = p.getBoundingBox();
  return { d: p.toPathData(2), width: f.getAdvanceWidth(str, size), bb };
}

const MARK = 128, GAP = 26, SIZE = 86;
const baseline = 64 + SIZE * 0.36; // optically centre the lowercase on the bubble
const hey = text(black, "Hey", MARK + GAP, baseline, SIZE);
const joy = text(black, "Joy", MARK + GAP + hey.width + SIZE * 0.2, baseline, SIZE); // a slightly tighter word space
const textRight = Math.ceil(Math.max(hey.bb.x2, joy.bb.x2));
const tag = text(bold, "Go with Joy", MARK + GAP + 3, baseline + 52, 30);

function lockup({ dark = false, tagline = false }) {
  const ink = dark ? COLORS.inkDark : COLORS.ink;
  const muted = dark ? COLORS.mutedDark : COLORS.muted;
  const w = Math.max(textRight, Math.ceil(tag.bb.x2)) + 4;
  const h = tagline ? Math.ceil(Math.max(128, tag.bb.y2 + 6)) : 128;
  const yMark = tagline ? (h - 128) / 2 : 0;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" role="img" aria-label="Hey Joy${tagline ? " — Go with Joy" : ""}">
  <g transform="translate(0 ${yMark})">${markSvgInner("hj")}</g>
  <linearGradient id="hj-t" x1="${joy.bb.x1}" y1="${joy.bb.y1}" x2="${joy.bb.x2}" y2="${joy.bb.y2}" gradientUnits="userSpaceOnUse">
    <stop offset="0" stop-color="${COLORS.from}"/><stop offset="1" stop-color="${COLORS.to}"/>
  </linearGradient>
  <g transform="translate(0 ${tagline ? yMark - 18 : 0})">
    <path d="${hey.d}" fill="${ink}"/>
    <path d="${joy.d}" fill="url(#hj-t)"/>
  </g>
  ${tagline ? `<path d="${tag.d}" transform="translate(0 ${yMark - 18})" fill="${muted}"/>` : ""}
</svg>`;
}

const mark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" width="128" height="128" role="img" aria-label="Hey Joy">${markSvgInner("hj")}</svg>`;
const files = {
  "heyjoy-mark.svg": mark,
  "heyjoy-logo.svg": lockup({}),
  "heyjoy-logo-dark.svg": lockup({ dark: true }),
  "heyjoy-logo-tagline.svg": lockup({ tagline: true }),
  "heyjoy-logo-tagline-dark.svg": lockup({ dark: true, tagline: true }),
};
for (const [name, svg] of Object.entries(files)) writeFileSync(`${out}/${name}`, svg);

// App-icon style mark on a soft background (for app stores / home screens), plus PNGs.
const appIcon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><rect width="512" height="512" rx="112" fill="#FFF4EC"/><svg x="72" y="80" width="368" height="368" viewBox="0 0 128 128">${markSvgInner("ai")}</svg></svg>`;
writeFileSync(`${out}/heyjoy-app-icon.svg`, appIcon);
await sharp(Buffer.from(appIcon)).resize(1024, 1024).png().toFile(`${out}/heyjoy-app-icon-1024.png`);
await sharp(Buffer.from(appIcon)).resize(180, 180).png().toFile(`${out}/apple-touch-icon.png`);
await sharp(Buffer.from(mark)).resize(512, 512).png().toFile(`${out}/heyjoy-mark-512.png`);
for (const [name, svg] of Object.entries(files)) {
  if (name.startsWith("heyjoy-logo")) await sharp(Buffer.from(svg), { density: 300 }).png().toFile(`${out}/${name.replace(".svg", ".png")}`);
}

// When building the app's own brand folder, also refresh the favicon, home-screen icon and the header logo
// component, so everything stays in sync with mark.mjs.
if (out === "public/brand") {
  copyFileSync(`${out}/heyjoy-mark.svg`, "public/favicon.svg");
  renameSync(`${out}/apple-touch-icon.png`, "public/apple-touch-icon.png");
  const jb = joy.bb;
  const artwork = (
    markSvgInner("hjx") +
    `<linearGradient id="hjx-t" x1="${jb.x1.toFixed(1)}" y1="${jb.y1.toFixed(1)}" x2="${jb.x2.toFixed(1)}" y2="${jb.y2.toFixed(1)}" gradientUnits="userSpaceOnUse">` +
    `<stop offset="0" stop-color="${COLORS.from}"/><stop offset="1" stop-color="${COLORS.to}"/></linearGradient>` +
    `<path class="logo-hey" d="${hey.d}"/><path d="${joy.d}" fill="url(#hjx-t)"/>`
  ).replace(/\s+/g, " ");
  const w = textRight + 4;
  writeFileSync(
    "src/components/Logo.tsx",
    `// Hey Joy logo (mark + wordmark). Generated by \`npm run brand\` from scripts/brand — don't edit by hand.
// The "Hey" colour comes from CSS (.logo-hey), so it follows the light/dark theme.
const ARTWORK = ${JSON.stringify(artwork)};

export default function Logo({ height = 34 }: { height?: number }) {
  return (
    <svg
      className="logo"
      viewBox="0 0 ${w} 128"
      height={height}
      width={(height * ${w}) / 128}
      role="img"
      aria-label="Hey Joy"
      // Static, trusted artwork generated at build time (no user content).
      dangerouslySetInnerHTML={{ __html: ARTWORK }}
    />
  );
}
`,
  );
}

console.log("built", Object.keys(files).length + 4, "files; lockup width", textRight);
